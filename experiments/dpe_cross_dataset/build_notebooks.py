"""Build the two Kaggle notebooks of the cross-dataset experiment from the files in code/.

    python experiments/dpe_cross_dataset/build_notebooks.py

backbones_kaggle.ipynb  GPU T4 x2: data, timing smoke, two SubpopBench ERM backbones + features.
nested_kaggle.ipynb     CPU: strictly nested post-hoc study on attached backbone outputs, summary.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CODE = HERE / "code"


def writefile(target, source):
    return f'%%writefile "{target}"\n' + (CODE / source).read_text(encoding="utf-8")


def md(text):
    return dict(cell_type="markdown", metadata={}, source=text.strip("\n").splitlines(keepends=True))


def code(text):
    return dict(cell_type="code", metadata={}, execution_count=None, outputs=[],
                source=text.strip("\n").splitlines(keepends=True))


def notebook(cells, path):
    nb = dict(cells=cells, nbformat=4, nbformat_minor=5,
              metadata=dict(kernelspec=dict(display_name="Python 3", language="python", name="python3"),
                            language_info=dict(name="python")))
    path.write_text(json.dumps(nb, indent=1), encoding="utf-8")
    print("wrote", path, len(cells), "cells")


